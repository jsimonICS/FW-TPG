"""Build the tpg FPGA design and embed the .fwfpga in a C header for tpg_fpga.

The design source lives in this repo (fpga/tpg); wilifpga's tools only look in
wilifpga/designs/, so this links wilifpga/designs/tpg -> fpga/tpg first (a
directory junction on Windows, a symlink elsewhere) and keeps the link out of
wilifpga's git status. Then `fwfpga build tpg` (synthesis, place and route,
timing check, pack, container check) and the header.

Needs the wilifpga toolchain: `wilifpga/tools/fwfpga toolchain install`.
--no-build embeds the existing build output instead (no toolchain needed).
"""
import argparse
import os
import pathlib
import struct
import subprocess
import sys

MAGIC = b"FW2FPGA\0"
HEADER_LEN = 256


def ensure_link(wilifpga, design_src, name):
    link = wilifpga / "designs" / name
    if not link.exists():
        if os.name == "nt":
            subprocess.run(["cmd", "/c", "mklink", "/J", str(link), str(design_src)],
                           check=True, stdout=subprocess.DEVNULL)
        else:
            link.symlink_to(design_src, target_is_directory=True)
    elif link.resolve() != design_src.resolve():
        sys.exit(f"{link} exists but does not point at {design_src}")
    exclude = wilifpga / ".git" / "info" / "exclude"
    entry = f"/designs/{name}"
    if exclude.parent.is_dir():
        lines = exclude.read_text().splitlines() if exclude.exists() else []
        if entry not in lines:
            with exclude.open("a") as f:
                f.write(f"\n{entry}\n")


def parse_header(data):
    if len(data) < HEADER_LEN or data[:8] != MAGIC:
        sys.exit("not a .fwfpga file (bad magic)")
    manifest_len, bitstream_len = struct.unpack_from("<II", data, 12)
    if len(data) != HEADER_LEN + manifest_len + bitstream_len:
        sys.exit("bad .fwfpga length")
    name = data[56:88].split(b"\0", 1)[0].decode("ascii")
    design_id, version = struct.unpack_from("<HH", data, 216)
    return name, design_id, version


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--wilifpga", required=True, type=pathlib.Path)
    ap.add_argument("--design-src", required=True, type=pathlib.Path)
    ap.add_argument("--name", default="tpg")
    ap.add_argument("--out", required=True, type=pathlib.Path)
    ap.add_argument("--no-build", action="store_true")
    a = ap.parse_args()

    wilifpga = a.wilifpga.resolve()
    if not (wilifpga / "tools" / "fwfpga.py").is_file():
        sys.exit(f"{wilifpga} is not a wilifpga checkout (git clone https://github.com/freewili/wilifpga)")
    if not a.no_build:
        ensure_link(wilifpga, a.design_src.resolve(), a.name)
        subprocess.run([sys.executable, "tools/fwfpga.py", "build", a.name], cwd=wilifpga, check=True)

    path = wilifpga / "build" / "designs" / a.name / f"{a.name}.fwfpga"
    data = path.read_bytes()
    name, design_id, version = parse_header(data)

    rows = [", ".join(f"0x{b:02X}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(
        f"/* Generated by gen_fwfpga_header.py from {path.name} - do not edit. */\n"
        "#pragma once\n#include <stdint.h>\n\n"
        f"#define TPG_FWFPGA_NAME      \"{name}\"\n"
        f"#define TPG_FWFPGA_DESIGN_ID {design_id}u\n"
        f"#define TPG_FWFPGA_VERSION   {version}u\n"
        f"#define TPG_FWFPGA_LEN       {len(data)}u\n"
        f"#define TPG_FWFPGA_HEADER_LEN {HEADER_LEN}u\n\n"
        "static const uint8_t TPG_FWFPGA[TPG_FWFPGA_LEN] = {\n    "
        + ",\n    ".join(rows) + "\n};\n")
    print(f"embedded {path} ({len(data)} bytes, {name} id {design_id} v{version}) -> {a.out}")


if __name__ == "__main__":
    main()
