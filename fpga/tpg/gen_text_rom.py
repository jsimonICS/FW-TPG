#!/usr/bin/env python3
"""Generate the tpg design's text ROMs and the testbench's text model.

Inputs (read, never edited):
  wilibsp/bsp/display/font5x7.c   the FW2 UI's classic 5x7 font (MIT, wilibsp
                                  LICENSE), chars 0x20..0x7E, column-major,
                                  bit 0 = top row
  apps/tpg/common/tpg_patterns.c  the pattern names shared with the OG and
                                  ZoomIO builds (patterns 0..8)

Outputs (checked in; rerun this after changing a name, the timing line or the
font):
  tpg_text_rom.v          module tpg_text_rom: the label ROM (glyph index per
                          {row select, pattern, column}) and the font ROM
                          (one 8-pixel row per {glyph, glyph row}), both
                          synchronous-read so yosys puts them in block RAM
  tb/tpg_text_model.vh    functions the testbench uses to build its own
                          expectation: the raw font columns exactly as in
                          font5x7.c and the label strings, so the design's
                          transposition, centering and pipelining are checked
                          rather than copied

Text layout (user_core.v): 40 x 30 cells of 8 x 8 pixels, a pixel being 4
clocks; a glyph occupies pixel columns 1..5 and rows 0..6 of its cell. Label
row 0 (cell row 24) is the pattern name, label row 1 (cell row 25) the timing
line, each centered: first column (40 - len) // 2.
"""
import argparse
import pathlib
import re
import sys

COLS = 40
FIRST = 0x20
LAST = 0x7E
FOCUS_NAME = "FOCUS (H)"          # pattern 9, FPGA only
TIMING = "15.73 KHZ  60.05 HZ"    # 63.56 us lines, 262-line fields
PATTERN_SLOTS = 16                # pat_cur is 4 bits; 10..15 have no name

HERE = pathlib.Path(__file__).resolve().parent
REPO = HERE.parent.parent


def read_font(path):
    glyphs = {}
    pat = re.compile(r"\{\s*((?:0x[0-9A-Fa-f]{2}\s*,\s*){4}0x[0-9A-Fa-f]{2})\s*\}\s*,?\s*//\s*0x([0-9A-Fa-f]{2})")
    for m in pat.finditer(path.read_text(encoding="utf-8")):
        glyphs[int(m.group(2), 16)] = [int(v, 16) for v in m.group(1).split(",")]
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        sys.exit(f"{path}: no glyph for {', '.join(hex(c) for c in missing)}")
    return glyphs


def read_names(path):
    names = re.findall(r'\[TPG_PATTERN_\w+\]\s*=\s*"([^"]*)"', path.read_text(encoding="utf-8"))
    if len(names) != 9:
        sys.exit(f"{path}: expected 9 pattern names, found {len(names)}")
    return names


def check_text(s):
    if len(s) > COLS:
        sys.exit(f"{s!r} is longer than {COLS} columns")
    bad = [c for c in s if not FIRST <= ord(c) <= LAST]
    if bad:
        sys.exit(f"{s!r}: no glyph for {bad!r}")


def start_col(s):
    return (COLS - len(s)) // 2


def font_rows(glyphs):
    """1024 entries {glyph[6:0], row[2:0]}: bit n = pixel column n of the cell."""
    rom = [0] * 1024
    for code in range(FIRST, LAST + 1):
        cols = glyphs[code]
        for row in range(7):
            bits = 0
            for c in range(5):
                if (cols[c] >> row) & 1:
                    bits |= 1 << (c + 1)
            rom[((code - FIRST) << 3) | row] = bits
    return rom


def label_rom(names):
    """2048 entries {sel, pattern[3:0], column[5:0]}: glyph index, 0 = space."""
    rom = [0] * 2048
    for pat in range(PATTERN_SLOTS):
        for sel, text in ((0, names[pat]), (1, TIMING)):
            s0 = start_col(text)
            for i, ch in enumerate(text):
                rom[(sel << 10) | (pat << 6) | (s0 + i)] = ord(ch) - FIRST
    return rom


def mem_init(name, width, rom):
    out = []
    per = 8
    for base in range(0, len(rom), per):
        out.append("  " + " ".join(f"{name}[{base + k}] = {width}'h{rom[base + k]:02X};"
                                    for k in range(per)))
    return "\n".join(out)


def verilog_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--font", type=pathlib.Path, default=REPO / "wilibsp/bsp/display/font5x7.c")
    ap.add_argument("--patterns", type=pathlib.Path, default=REPO / "apps/tpg/common/tpg_patterns.c")
    ap.add_argument("--out-dir", type=pathlib.Path, default=HERE)
    a = ap.parse_args()

    glyphs = read_font(a.font)
    names = read_names(a.patterns) + [FOCUS_NAME] + [""] * (PATTERN_SLOTS - 10)
    for s in names + [TIMING]:
        check_text(s)

    texts = [s for s in names + [TIMING] if s]
    box_c0 = min(start_col(s) for s in texts)
    box_c1 = max(start_col(s) + len(s) for s in texts)

    rom_v = f"""// tpg_text_rom.v - GENERATED by gen_text_rom.py; do not edit.
//
// Glyphs: wilibsp/bsp/display/font5x7.c (MIT License, Copyright (c) 2026
// Dave Robins; see wilibsp/LICENSE), transposed to rows. Labels: pattern
// names from apps/tpg/common/tpg_patterns.c plus "{FOCUS_NAME}", and the
// timing line "{TIMING}", centered in {COLS} columns.
// Text box columns (user_core.v TXT_BOX_*): {box_c0} .. {box_c1 - 1}.
module tpg_text_rom (
  input  wire        clk,
  input  wire [10:0] label_addr,   // {{timing row, pattern[3:0], column[5:0]}}
  output reg  [6:0]  label_q,      // glyph index (ASCII - 0x20); 0 = space
  input  wire [9:0]  font_addr,    // {{glyph[6:0], glyph row[2:0]}}
  output reg  [7:0]  font_q        // bit n = pixel column n of the cell
);

reg [6:0] label_rom [0:2047];
reg [7:0] font_rom  [0:1023];

initial begin
{mem_init("label_rom", 7, label_rom(names))}
{mem_init("font_rom", 8, font_rows(glyphs))}
end

always @(posedge clk) begin
  label_q <= label_rom[label_addr];
  font_q  <= font_rom[font_addr];
end

endmodule
"""

    font_cases = "\n".join(
        f"      8'h{code:02X}: tm_font_col = 40'h{''.join(f'{v:02X}' for v in reversed(glyphs[code]))};"
        for code in range(FIRST, LAST + 1))
    name_cases = "\n".join(f"      {pat}: s = {verilog_str(n)};" for pat, n in enumerate(names) if n)
    model = f"""// tpg_text_model.vh - GENERATED by gen_text_rom.py; do not edit.
// Raw data for the testbench's own text model: font columns exactly as in
// wilibsp/bsp/display/font5x7.c (bit 0 = top row) and the label strings.

// Column c (0..4) of the glyph for ASCII `ch`.
function [7:0] tm_font(input integer ch, input integer c);
  reg [39:0] tm_font_col;
  begin
    case (ch)
{font_cases}
      default: tm_font_col = 40'h0;
    endcase
    tm_font = tm_font_col[c * 8 +: 8];
  end
endfunction

// Label text: sel 0 = pattern name, 1 = timing line. Returns the string
// right-aligned in 40 bytes (Verilog string rules) and its length.
function integer tm_len(input integer pat, input integer sel);
  reg [8*{COLS}-1:0] s;
  integer n;
  begin
    s = tm_text(pat, sel);
    n = 0;
    while (n < {COLS} && s[n * 8 +: 8] != 8'h00) n = n + 1;
    tm_len = n;
  end
endfunction

function [8*{COLS}-1:0] tm_text(input integer pat, input integer sel);
  reg [8*{COLS}-1:0] s;
  begin
    s = 0;
    if (sel == 1) s = {verilog_str(TIMING)};
    else case (pat)
{name_cases}
      default: s = 0;
    endcase
    tm_text = s;
  end
endfunction

// The i-th character (0 = leftmost) of a label.
function integer tm_char(input integer pat, input integer sel, input integer i);
  reg [8*{COLS}-1:0] s;
  integer n;
  begin
    s = tm_text(pat, sel);
    n = tm_len(pat, sel);
    tm_char = s[(n - 1 - i) * 8 +: 8];
  end
endfunction
"""
    a.out_dir.mkdir(parents=True, exist_ok=True)
    (a.out_dir / "tpg_text_rom.v").write_text(rom_v, newline="\n")
    (a.out_dir / "tb").mkdir(exist_ok=True)
    (a.out_dir / "tb" / "tpg_text_model.vh").write_text(model, newline="\n")
    print(f"wrote tpg_text_rom.v and tb/tpg_text_model.vh; text box columns {box_c0}..{box_c1 - 1}")


if __name__ == "__main__":
    main()
