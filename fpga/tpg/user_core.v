// user_core.v - design "tpg": 15 kHz RGB test pattern generator for the
// FreeWili 2, the FPGA port of apps/tpg/main (OG, PIO + DMA) and
// fw2/apps/tpg_zio (FW2, ZoomIO).
//
// Same signal as those two: a fixed 262-line non-interlaced RS-170-style
// field (apps/tpg/main/video_timing.h), 3 bits per color into the external
// 120/240/470 ohm ladders, active-low composite sync on GPIO27, and the same
// nine patterns in the same order (apps/tpg/common/tpg_patterns.h). FPGA
// only: pattern 9, a screen of "H" (focus), and a text overlay naming the
// pattern and the timing (tpg_text_rom.v, generated by gen_text_rom.py).
//
// Clock is 25 MHz (design.toml), 40 ns per clock. Every timing constant is
// the video_timing.h value in ns rounded half up to whole clocks, so nothing
// is more than 20 ns off (HSYNC 4.72 us for 4.70, EQ 2.32 us for 2.30); line
// (1589 clocks = 63.56 us, 15.73 kHz) and field (262 lines, 60.05 Hz) are
// exact. (59.94 Hz is the 262.5-line interlaced rate; this is progressive.)
//
// One deliberate difference from the OG: x = 0 here is the leading (falling)
// edge of horizontal sync and the equalizing / broad pulses start on it, as
// RS-170 has them. The OG starts each line with its front porch, so its
// vertical interval is shifted 1.52 us against the hsync grid.
//
// Registers (user window 0x10-0x5F):
//   0x10 PATTERN  rw  tpg_pattern_id_t 0..8, or 9 = focus ("H" screen);
//                     anything else shows black. Takes effect at the next
//                     field start (no torn field).
//   0x11 FIELDS   ro  field counter, +1 per field (60.05 Hz), wraps.
//   0x12 COUNT    ro  number of patterns (10).
//   0x13 CONTROL  rw  bit 0: text overlay (pattern name + timing), reset 1.
//                     Takes effect at the next field start.
// All reads are free of side effects (design contract rule 7).
//
// Outputs are registered, so every pin changes on the same clock edge.
`include "fw2_profile.vh"

module user_core
(
  input  wire       clk,
  input  wire       rst_n,
  input  wire [9:0] hdr_in,
  output wire [9:0] hdr_out,
  output wire [9:0] hdr_oe,
  input  wire [9:0] rp_in,
  output wire [9:0] rp_out,
  input  wire [6:0] reg_addr,
  input  wire [7:0] reg_wdata,
  input  wire       reg_wr,
  input  wire       reg_rd,
  output wire [7:0] reg_rdata,
  input  wire [7:0] fifo_tx_data,
  input  wire       fifo_tx_valid,
  output wire       fifo_tx_ready,
  output wire [7:0] fifo_rx_data,
  output wire       fifo_rx_valid,
  input  wire       fifo_rx_ready
);

// --------------------------------------------------------------- timing
// Horizontal, in 40 ns clocks from the falling edge of hsync.
localparam [10:0] H_TOTAL   = 11'd1589;  // 63.56 us
localparam [10:0] HSYNC     = 11'd118;   // 4.72 us
localparam [10:0] ACT_START = 11'd235;   // hsync + back porch, 9.40 us
localparam [10:0] ACT_END   = 11'd1551;  // ACT_START + 1316 (52.64 us); front porch 38 = 1.52 us
localparam [10:0] HALF      = 11'd795;   // start of the second half-line pulse
localparam [10:0] EQ1_END   = 11'd58;    // equalizing pulse 2.32 us
localparam [10:0] EQ2_END   = 11'd853;   // HALF + 58
localparam [10:0] VS1_END   = 11'd677;   // broad pulse = half line - 118 (4.72 us serration)
localparam [10:0] VS2_END   = 11'd1471;  // H_TOTAL - 118

// Vertical, in lines: 0-2 pre-equalizing, 3-5 vsync, 6-8 post-equalizing,
// 9-18 blank, 19-259 active (241), 260-261 blank.
localparam [8:0] V_TOTAL     = 9'd262;
localparam [8:0] V_VS_FIRST  = 9'd3;
localparam [8:0] V_PEQ_FIRST = 9'd6;
localparam [8:0] V_BLK_FIRST = 9'd9;
localparam [8:0] V_ACT_FIRST = 9'd19;
localparam [8:0] V_ACT_LAST  = 9'd259;

// --------------------------------------------------------------- patterns
localparam [3:0] P_COLOR_BARS      = 4'd0;
localparam [3:0] P_RGB_GRADIENT    = 4'd1;
localparam [3:0] P_BW_GRADIENT     = 4'd2;
localparam [3:0] P_CHECKERBOARD    = 4'd3;
localparam [3:0] P_CROSSHATCH_DOTS = 4'd4;
localparam [3:0] P_RGB_CROSSHATCH  = 4'd5;
localparam [3:0] P_SOLID_RED       = 4'd6;
localparam [3:0] P_SOLID_BLUE      = 4'd7;
localparam [3:0] P_SOLID_GREEN     = 4'd8;
localparam [3:0] P_FOCUS           = 4'd9;    // FPGA only
localparam [3:0] P_BLACK           = 4'd15;   // out-of-range PATTERN value
localparam [7:0] PATTERN_COUNT     = 8'd10;

localparam [6:0] REG_PATTERN = 7'h10;
localparam [6:0] REG_FIELDS  = 7'h11;
localparam [6:0] REG_COUNT   = 7'h12;
localparam [6:0] REG_CONTROL = 7'h13;

// --------------------------------------------------------------- counters
reg [10:0] hcnt = 11'd0;
reg [8:0]  vcnt = 9'd0;

always @(posedge clk) begin
  if (!rst_n) begin
    hcnt <= 11'd0;
    vcnt <= 9'd0;
  end else if (hcnt == H_TOTAL - 11'd1) begin
    hcnt <= 11'd0;
    vcnt <= (vcnt == V_TOTAL - 9'd1) ? 9'd0 : vcnt + 9'd1;
  end else begin
    hcnt <= hcnt + 11'd1;
  end
end

wire field_start = (hcnt == 11'd0) && (vcnt == 9'd0);

// --------------------------------------------------------------- registers
reg [7:0] pattern = 8'h00;    // as written to 0x10
reg [3:0] pat_cur = 4'd0;     // what this field shows, latched at field start
reg [7:0] fields  = 8'h00;
reg       ovl     = 1'b1;     // CONTROL bit 0 as written
reg       ovl_cur = 1'b1;     // what this field shows, latched at field start

always @(posedge clk) begin
  if (!rst_n) begin
    pattern <= 8'h00;
    pat_cur <= P_COLOR_BARS;
    fields  <= 8'h00;
    ovl     <= 1'b1;
    ovl_cur <= 1'b1;
  end else begin
    if (reg_wr && reg_addr == REG_PATTERN)
      pattern <= reg_wdata;
    if (reg_wr && reg_addr == REG_CONTROL)
      ovl <= reg_wdata[0];
    if (field_start) begin
      pat_cur <= (pattern < PATTERN_COUNT) ? pattern[3:0] : P_BLACK;
      ovl_cur <= ovl;
      fields  <= fields + 8'd1;
    end
  end
end

assign reg_rdata = (reg_addr == REG_PATTERN) ? pattern :
                   (reg_addr == REG_FIELDS)  ? fields  :
                   (reg_addr == REG_COUNT)   ? PATTERN_COUNT :
                   (reg_addr == REG_CONTROL) ? {7'b0, ovl} : 8'h00;

// --------------------------------------------------------------- sync
wire vs_line = (vcnt >= V_VS_FIRST) && (vcnt < V_PEQ_FIRST);
wire eq_line = (vcnt < V_VS_FIRST) || ((vcnt >= V_PEQ_FIRST) && (vcnt < V_BLK_FIRST));
wire second_half = (hcnt >= HALF);

reg sync_on;
always @* begin
  if (vs_line)
    sync_on = (hcnt < VS1_END) || (second_half && (hcnt < VS2_END));
  else if (eq_line)
    sync_on = (hcnt < EQ1_END) || (second_half && (hcnt < EQ2_END));
  else
    sync_on = (hcnt < HSYNC);
end

// --------------------------------------------------------------- picture geometry
wire        active = (vcnt >= V_ACT_FIRST) && (vcnt <= V_ACT_LAST) &&
                     (hcnt >= ACT_START) && (hcnt < ACT_END);
wire [10:0] ax = hcnt - ACT_START;    // 0..1315 while active
wire [8:0]  ay = vcnt - V_ACT_FIRST;  // 0..240 while active

// Rows. Gradient steps of 241 / 8 = 30 lines and checker rows of
// 241 / 6 = 40 lines; the leftover line 240 folds into the last step / row
// (video_pattern.c). The step is the gradients' channel level, 0..7.
wire [2:0] grad_step = (ay < 9'd30)  ? 3'd0 : (ay < 9'd60)  ? 3'd1 :
                       (ay < 9'd90)  ? 3'd2 : (ay < 9'd120) ? 3'd3 :
                       (ay < 9'd150) ? 3'd4 : (ay < 9'd180) ? 3'd5 :
                       (ay < 9'd210) ? 3'd6 : 3'd7;
wire       row_odd = ((ay >= 9'd40)  && (ay < 9'd80))  ||
                     ((ay >= 9'd120) && (ay < 9'd160)) ||
                      (ay >= 9'd200);
// Crosshatch: a horizontal line every 40 lines (0, 40, ..., 240); dots on
// the two middle lines of each cell row (ay % 40 == 19 or 20).
wire grid_row = (ay == 9'd0)   || (ay == 9'd40)  || (ay == 9'd80)  || (ay == 9'd120) ||
                (ay == 9'd160) || (ay == 9'd200) || (ay == 9'd240);
wire dot_row  = (ay == 9'd19)  || (ay == 9'd20)  || (ay == 9'd59)  || (ay == 9'd60)  ||
                (ay == 9'd99)  || (ay == 9'd100) || (ay == 9'd139) || (ay == 9'd140) ||
                (ay == 9'd179) || (ay == 9'd180) || (ay == 9'd219) || (ay == 9'd220);

// Columns. 1316 active clocks don't divide by 8 or 3, so column c starts at
// ceil(c * 1316 / N): bars 165/164 clocks wide alternately, thirds 439/439/438.
wire [2:0] bar = (ax < 11'd165)  ? 3'd0 : (ax < 11'd329)  ? 3'd1 :
                 (ax < 11'd494)  ? 3'd2 : (ax < 11'd658)  ? 3'd3 :
                 (ax < 11'd823)  ? 3'd4 : (ax < 11'd987)  ? 3'd5 :
                 (ax < 11'd1152) ? 3'd6 : 3'd7;
wire [1:0] third = (ax < 11'd439) ? 2'd0 : (ax < 11'd878) ? 2'd1 : 2'd2;

// Crosshatch verticals: line k starts at round(k * 6540 ns), 8 clocks
// (320 ns) wide; the last one ends exactly at the end of the active region.
// Dot k starts at round(k * 6540 + 3280 ns), 8 clocks (300 ns -> 320 ns).
// A macro, not a function: iverilog evaluates functions in continuous
// assignments ~6x slower, and the testbench runs whole fields.
`define TPG_IN8(x, start) (((x) >= (start)) && ((x) < (start) + 11'd8))

wire [8:0] vl = { `TPG_IN8(ax, 11'd1308), `TPG_IN8(ax, 11'd1145), `TPG_IN8(ax, 11'd981),
                  `TPG_IN8(ax, 11'd818),  `TPG_IN8(ax, 11'd654),  `TPG_IN8(ax, 11'd491),
                  `TPG_IN8(ax, 11'd327),  `TPG_IN8(ax, 11'd164),  (ax < 11'd8) };
wire [7:0] dt = { `TPG_IN8(ax, 11'd1227), `TPG_IN8(ax, 11'd1063), `TPG_IN8(ax, 11'd900),
                  `TPG_IN8(ax, 11'd736),  `TPG_IN8(ax, 11'd573),  `TPG_IN8(ax, 11'd409),
                  `TPG_IN8(ax, 11'd246),  `TPG_IN8(ax, 11'd82) };
`undef TPG_IN8

// --------------------------------------------------------------- text
// 40 x 30 cells of 8 x 8 pixels, a pixel 4 clocks (160 ns) wide: 1280 of the
// 1316 active clocks, centered (18 clocks either side), and lines 0..239.
// The overlay box covers label cell rows 24 (pattern name) and 25 (timing)
// plus 3 blank lines above and below and ~3 pixels either side of the
// longest label (gen_text_rom.py prints its columns, 10..28).
localparam [10:0] TXT_X0     = 11'd18;
localparam [10:0] TXT_X1     = 11'd1298;                   // TXT_X0 + 40 * 32
localparam [3:0]  TXT_ROW_AB = 4'd12;                      // ay[7:4]: cell rows 24 and 25
localparam [10:0] TXT_BOX_X0 = TXT_X0 + 11'd320 - 11'd8;   // column 10, 3 px before its glyph
localparam [10:0] TXT_BOX_X1 = TXT_X0 + 11'd928 + 11'd4;   // column 29, 3 px past column 28's glyph
localparam [8:0]  TXT_BOX_Y0 = 9'd189;                     // cell row 24 starts at 192
localparam [8:0]  TXT_BOX_Y1 = 9'd210;                     // row 25's glyphs end at 206
localparam [6:0]  GLYPH_H    = 7'h28;                      // 'H' - 0x20

// The ROM reads take two clocks (label, then font), so the character is
// looked up one clock ahead: axn is the active x of the NEXT clock, and the
// font row arrives in the same clock as the stage-1 geometry of this one.
wire [10:0] axn       = hcnt - (ACT_START - 11'd1);
wire [10:0] txn       = axn - TXT_X0;
wire        grid_y    = (ay < 9'd240);                     // also false outside active lines
wire        label_row = grid_y && (ay[7:4] == TXT_ROW_AB);
wire        grid_xn   = (axn >= TXT_X0) && (axn < TXT_X1);
wire        box_xn    = (axn >= TXT_BOX_X0) && (axn < TXT_BOX_X1);   // label text only inside the box

wire [6:0] label_q;
wire [7:0] font_q;
reg  [1:0] a_src = 2'd0;      // char for the next clock: 0 none, 1 label, 2 'H'
always @(posedge clk)
  a_src <= (ovl_cur && label_row && box_xn)            ? 2'd1 :
           ((pat_cur == P_FOCUS) && grid_y && grid_xn) ? 2'd2 : 2'd0;
wire [6:0] glyph = (a_src == 2'd1) ? label_q : (a_src == 2'd2) ? GLYPH_H : 7'd0;

tpg_text_rom text_rom (
  .clk(clk),
  .label_addr({ay[3], pat_cur, txn[10:5]}),
  .label_q(label_q),
  .font_addr({glyph, ay[2:0]}),
  .font_q(font_q)
);

wire [10:0] tx     = ax - TXT_X0;                          // this clock, for stage 1
wire        grid_x = (ax >= TXT_X0) && (ax < TXT_X1);
wire        in_box = ovl_cur && (ay >= TXT_BOX_Y0) && (ay < TXT_BOX_Y1) &&
                     (ax >= TXT_BOX_X0) && (ax < TXT_BOX_X1);

// --------------------------------------------------------------- pipeline stage 1
// Register the geometry (and sync with it, so every pin keeps the same
// latency); the color mux then runs from flops. Without this stage the
// counter -> subtract -> compare -> mux path closed at only ~29.7 MHz.
reg       s_active = 1'b0, s_sync_on = 1'b0;
reg [2:0] s_bar = 3'd0;
reg [1:0] s_third = 2'd0;
reg       s_row_odd = 1'b0, s_grid_row = 1'b0, s_dot_row = 1'b0;
reg [8:0] s_vl = 9'd0;
reg [7:0] s_dt = 8'd0;
reg [2:0] s_grad = 3'd0;
reg [2:0] s_px = 3'd0;
reg       s_label = 1'b0, s_grid = 1'b0, s_box = 1'b0;

always @(posedge clk) begin
  s_active   <= active;
  s_sync_on  <= sync_on;
  s_bar      <= bar;
  s_third    <= third;
  s_row_odd  <= row_odd;
  s_grid_row <= grid_row;
  s_dot_row  <= dot_row;
  s_vl       <= vl;
  s_dt       <= dt;
  s_grad     <= grad_step;
  s_px       <= tx[4:2];
  s_label    <= label_row && grid_x;
  s_grid     <= grid_y && grid_x;
  s_box      <= in_box;
end

// RGB crosshatch cycles its verticals red, green, blue, white (k % 4).
wire xh_red   = s_vl[0] | s_vl[4] | s_vl[8];
wire xh_green = s_vl[1] | s_vl[5];
wire xh_blue  = s_vl[2] | s_vl[6];
wire xh_white = s_vl[3] | s_vl[7];

// --------------------------------------------------------------- color (stage 2)
// font_q is the glyph row for this clock's cell (looked up a clock ahead).
wire txt_px = font_q[s_px];

reg [2:0] r, g, b;
always @* begin
  r = 3'd0; g = 3'd0; b = 3'd0;
  if (s_active && s_box) begin
    // Overlay: white label text on black.
    r = {3{s_label & txt_px}}; g = r; b = r;
  end else if (s_active) begin
    case (pat_cur)
      // white, yellow, cyan, green, magenta, red, blue, black
      P_COLOR_BARS:      begin r = {3{~s_bar[1]}}; g = {3{~s_bar[2]}}; b = {3{~s_bar[0]}}; end
      P_RGB_GRADIENT:    begin
                           r = (s_third == 2'd0) ? s_grad : 3'd0;
                           g = (s_third == 2'd1) ? s_grad : 3'd0;
                           b = (s_third == 2'd2) ? s_grad : 3'd0;
                         end
      P_BW_GRADIENT:     begin r = s_grad; g = s_grad; b = s_grad; end
      P_CHECKERBOARD:    begin r = {3{~(s_row_odd ^ s_bar[0])}}; g = r; b = r; end
      P_CROSSHATCH_DOTS: begin r = {3{s_grid_row | (|s_vl) | (s_dot_row & (|s_dt))}}; g = r; b = r; end
      P_RGB_CROSSHATCH:  begin
                           r = {3{s_grid_row | xh_red   | xh_white}};
                           g = {3{s_grid_row | xh_green | xh_white}};
                           b = {3{s_grid_row | xh_blue  | xh_white}};
                         end
      P_SOLID_RED:       r = 3'd7;
      P_SOLID_BLUE:      b = 3'd7;
      P_SOLID_GREEN:     g = 3'd7;
      P_FOCUS:           begin r = {3{s_grid & txt_px}}; g = r; b = r; end
      default:           ;   // P_BLACK
    endcase
  end
end

// --------------------------------------------------------------- outputs
// Pin map (design.toml): MSB first per channel, CSYNC active low.
reg [9:0] out_q = 10'b1 << `FW2_SIG_GPIO27;   // black, sync idle

always @(posedge clk) begin
  if (!rst_n) begin
    out_q <= 10'b1 << `FW2_SIG_GPIO27;
  end else begin
    out_q[`FW2_SIG_UART_TX]  <= b[2];
    out_q[`FW2_SIG_UART_RX]  <= b[1];
    out_q[`FW2_SIG_UART_CTS] <= b[0];
    out_q[`FW2_SIG_UART_RTS] <= g[2];
    out_q[`FW2_SIG_SPI_MISO] <= g[1];
    out_q[`FW2_SIG_SPI_CS]   <= g[0];
    out_q[`FW2_SIG_SPI_SCLK] <= r[2];
    out_q[`FW2_SIG_SPI_MOSI] <= r[1];
    out_q[`FW2_SIG_GPIO26]   <= r[0];
    out_q[`FW2_SIG_GPIO27]   <= ~s_sync_on;
  end
end

assign hdr_out = out_q;
assign hdr_oe  = 10'h3FF;   // all ten are FPGA_OUT

// Unused ports: tie off (keeps verilator -Wall clean)
assign rp_out        = 10'b0;
assign fifo_tx_ready = 1'b0;
assign fifo_rx_data  = 8'h00;
assign fifo_rx_valid = 1'b0;

/* verilator lint_off UNUSEDSIGNAL */
wire unused = &{1'b0, hdr_in, rp_in, reg_rd, fifo_tx_data, fifo_tx_valid, fifo_rx_ready,
                tx[10:5], tx[1:0], txn[4:0]};
/* verilator lint_on UNUSEDSIGNAL */

endmodule
